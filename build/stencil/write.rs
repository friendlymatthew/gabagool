use std::{fmt::Write, fs, path::Path};

use object::{macho, RelocationFlags};

use super::extract::Stencil;

pub(super) fn generate(stencils: &[Stencil<'_>], output: &Path) {
    let mut source = String::from(
        r#"// Generated by build/stencil/write.rs. Do not edit.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PatchValue {
    Continue,
    Parameter(usize),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PatchEncoding {
    /// changes a jump so it goes to the next stencil.
    Branch26,

    /// finds the memory page containing our data slot
    /// used together with GotPageOff12
    GotPage21,

    /// finds the slot within that page and loads the value stored there
    GotPageOff12,
}

#[derive(Debug)]
pub struct Patch {
    pub offset: usize,
    pub value: PatchValue,
    pub encoding: PatchEncoding,
    pub addend: i64,
}

#[derive(Debug)]
pub struct Stencil {
    pub code: &'static [u8],
    pub patches: &'static [Patch],
}

/// One use of a stencil, with its numbered parameter values.
#[derive(Debug)]
pub struct StencilInstance<'a> {
    pub stencil: &'a Stencil,
    pub parameters: alloc::vec::Vec<u64>,
}

"#,
    );

    for stencil in stencils {
        let name = stencil
            .function_name
            .trim_start_matches('_')
            .to_ascii_uppercase();

        writeln!(source, "pub static STENCIL_{name}: Stencil = Stencil {{").unwrap();
        writeln!(source, "        code: &{:?},", stencil.code).unwrap();
        writeln!(source, "        patches: &[").unwrap();

        for patch in &stencil.patches {
            let is_parameter = patch.symbol.starts_with("__JIT_PARAM_");

            let value = if let Some(index) = patch.symbol.strip_prefix("__JIT_PARAM_") {
                let index: usize = index.parse().expect("invalid stencil parameter index");

                assert!(index < usize::MAX, "stencil parameter index is too large");

                format!("Parameter({index})")
            } else if patch.symbol == "__JIT_CONTINUE" {
                String::from("Continue")
            } else {
                panic!("unsupported stencil placeholder {}", patch.symbol);
            };

            let encoding = match (is_parameter, patch.relocation.flags()) {
                (
                    false,
                    RelocationFlags::MachO {
                        r_type: macho::ARM64_RELOC_BRANCH26,
                        r_pcrel: true,
                        r_length: 2,
                    },
                ) => "Branch26",
                (
                    true,
                    RelocationFlags::MachO {
                        r_type: macho::ARM64_RELOC_GOT_LOAD_PAGE21,
                        r_pcrel: true,
                        r_length: 2,
                    },
                ) => "GotPage21",
                (
                    true,
                    RelocationFlags::MachO {
                        r_type: macho::ARM64_RELOC_GOT_LOAD_PAGEOFF12,
                        r_pcrel: false,
                        r_length: 2,
                    },
                ) => "GotPageOff12",
                (_, flags) => panic!(
                    "unsupported relocation in {} at {}: {flags:?}",
                    stencil.function_name, patch.offset
                ),
            };

            writeln!(
                source,
                "            Patch {{ offset: {}, value: PatchValue::{value}, encoding: PatchEncoding::{encoding}, addend: {} }},",
                patch.offset,
                patch.relocation.addend(),
            )
            .unwrap();
        }

        writeln!(source, "        ],\n}};\n").unwrap();
    }

    fs::write(output, source).expect("failed to write generated stencils");
}
