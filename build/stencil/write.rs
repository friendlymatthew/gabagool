use std::{fmt::Write, fs, path::Path};

use object::{macho, RelocationFlags};

use super::extract::Stencil;

pub(super) fn generate(stencils: &[Stencil<'_>], output: &Path) {
    let mut source = String::from(
        r#"// Generated by build/stencil/write.rs. Do not edit.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PatchValue { Continue, LocalA, LocalB }

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PatchEncoding {
    /// changes a jump so it goes to the next stencil.
    Branch26,

    /// finds the memory page containing our local-index slot
    /// used together with GotPageOff12
    GotPage21,

    /// finds the slot within that page and loads the local index stored there
    GotPageOff12,
}

#[derive(Debug)]
pub struct Patch {
    pub offset: usize,
    pub value: PatchValue,
    pub encoding: PatchEncoding,
    pub addend: i64,
}

#[derive(Debug)]
pub struct Stencil {
    pub name: &'static str,
    pub code: &'static [u8],
    pub patches: &'static [Patch],
}

/// Values supplied by one IR operation when it uses a stencil.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StencilOperands {
    None,
    LocalGet { local_i: u32 },
    LocalGet2 { local_i_a: u32, local_i_b: u32 },
}

#[derive(Debug)]
pub struct StencilInstance<'a> {
    pub stencil: &'a Stencil,
    pub operands: StencilOperands,
}

pub static STENCILS: &[Stencil] = &[
"#,
    );

    for stencil in stencils {
        writeln!(source, "    Stencil {{").unwrap();
        writeln!(source, "        name: {:?},", stencil.function_name).unwrap();
        writeln!(source, "        code: &{:?},", stencil.code).unwrap();
        writeln!(source, "        patches: &[").unwrap();

        for patch in &stencil.patches {
            let value = match patch.symbol {
                "__JIT_CONTINUE" => "Continue",
                "__JIT_LOCAL_A" => "LocalA",
                "__JIT_LOCAL_B" => "LocalB",
                other => panic!("unsupported stencil placeholder {other}"),
            };

            let encoding = match (value, patch.relocation.flags()) {
                (
                    "Continue",
                    RelocationFlags::MachO {
                        r_type: macho::ARM64_RELOC_BRANCH26,
                        r_pcrel: true,
                        r_length: 2,
                    },
                ) => "Branch26",
                (
                    "LocalA" | "LocalB",
                    RelocationFlags::MachO {
                        r_type: macho::ARM64_RELOC_GOT_LOAD_PAGE21,
                        r_pcrel: true,
                        r_length: 2,
                    },
                ) => "GotPage21",
                (
                    "LocalA" | "LocalB",
                    RelocationFlags::MachO {
                        r_type: macho::ARM64_RELOC_GOT_LOAD_PAGEOFF12,
                        r_pcrel: false,
                        r_length: 2,
                    },
                ) => "GotPageOff12",
                (_, flags) => panic!(
                    "unsupported relocation in {} at {}: {flags:?}",
                    stencil.function_name, patch.offset
                ),
            };

            writeln!(
                source,
                "            Patch {{ offset: {}, value: PatchValue::{value}, encoding: PatchEncoding::{encoding}, addend: {} }},",
                patch.offset,
                patch.relocation.addend(),
            )
            .unwrap();
        }

        writeln!(source, "        ],\n    }},").unwrap();
    }

    source.push_str("];\n");

    fs::write(output, source).expect("failed to write generated stencils");
}
